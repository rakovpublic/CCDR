def _v57_generic_gate(path, required_bool, required_numeric, label, thresholds=None):
    thresholds=thresholds or {}
    row=_v57_artifact_row(path)
    missing=[]
    for k in required_bool:
        if not _v57_truthy(row.get(k)): missing.append(k)
    for k in required_numeric:
        if _v57_to_float(row.get(k)) is None: missing.append(k)
    for k,(op,val) in thresholds.items():
        x=_v57_to_float(row.get(k))
        if x is None: continue
        if op=='>=' and not (x>=val): missing.append(f'{k}_ge_{val}')
