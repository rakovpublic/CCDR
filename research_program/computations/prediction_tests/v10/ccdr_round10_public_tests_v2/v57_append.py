# ---------- P36 high-z autonomous raw-row builder ----------
def _v57_autobuild_p36_highz_rows(max_files=300):
    """Build a raw high-z object-row artifact automatically from cache/public rows.

    This intentionally refuses generated outputs/summaries/reanalysis files.  It
    accepts raw-looking catalog/cache files when columns can be normalized to
    source_group, object_id, z, vrot_km_s, radius_kpc, raw_source_file.
    """
    import csv, json, hashlib, math
    out_csv=_v57_inputs_dir()/ 'p36_highz_object_rows_raw_v57_AUTO.csv'
    diag_path=_v57_outputs_dir()/ 'p36_highz_autobuild_v57.json'
    rejected_path=_v57_outputs_dir()/ 'p36_highz_rejected_rows_v57.json'
    patterns=['*kges*.*','*kross*.*','*kmos3d*.*','*sami*.*','*highz*.*','*vrot*.*','*rotation*.*']
    files=[]
    for p in _v57_candidate_files(patterns, roots=[_v57_inputs_dir(), _v57_measurements_dir(), _v57_cache_dir()], max_files=max_files):
        s=str(p).lower().replace('\\','/')
        if any(x in s for x in ['/outputs/','summary','template','fill','example','reanalysis','normalized','rejected']):
            continue
        if p.suffix.lower() not in ['.csv','.tsv','.txt','.dat','.json']:
            continue
        files.append(p)

    src_alias=['source_group','source','survey','catalogue','catalog','dataset','sample','SOURCE','Survey','Catalogue']
    obj_alias=['object_id','object','id','ID','name','galaxy','target','target_id','gal_id','kid','KID','KROSS_ID','KGES_ID','OBJID','objid']
    z_alias=['z','Z','redshift','z_best','zspec','z_spec','zphot','z_phot','REDSHIFT']
    v_alias=['vrot_km_s','Vrot','VROT','v_rot_km_s','vrot','v_rot','vcirc','v_circ','vmax','Vmax','vmax_km_s','velocity_km_s','v_km_s','V_2.2','V2.2','Vflat','v_flat','Vel','VEL']
    r_alias=['radius_kpc','R_kpc','r_kpc','R','radius','r_d_kpc','rd_kpc','R_d','Rd','r_eff_kpc','Re_kpc','r_half_kpc','scale_radius_kpc','R22','R_2.2']

    def first(row, aliases):
        for a in aliases:
            if a in row and str(row.get(a,'')).strip() not in ['', 'nan', 'None', 'NULL']:
                return row.get(a)
        # loose normalized key pass
        norm={re.sub(r'[^a-z0-9]+','',str(k).lower()):v for k,v in row.items()}
        for a in aliases:
            k=re.sub(r'[^a-z0-9]+','',str(a).lower())
            if k in norm and str(norm[k]).strip() not in ['', 'nan', 'None', 'NULL']:
                return norm[k]
        return None

    def iter_rows(p):
        try:
            txt=p.read_text(encoding='utf-8', errors='replace')
            if p.suffix.lower()=='.json':
                obj=json.loads(txt)
                if isinstance(obj,dict):
                    rows=obj.get('rows') or obj.get('objects') or obj.get('data') or obj.get('table') or []
                    if isinstance(rows,dict): rows=list(rows.values())
                elif isinstance(obj,list): rows=obj
                else: rows=[]
                for r in rows:
                    if isinstance(r,dict): yield r
            else:
                # Strip comment lines often present in catalogue text.
                lines=[ln for ln in txt.splitlines() if ln.strip() and not ln.lstrip().startswith(('#',';'))]
                if not lines: return
                sample='\n'.join(lines[:20])
                try:
                    delim=csv.Sniffer().sniff(sample, delimiters=',\t;| ').delimiter
                    # Whitespace-delimited tables usually need explicit split; csv with space is fragile.
                    if delim==' ' and any('\t' in ln for ln in lines[:5]): delim='\t'
                except Exception:
                    delim='\t' if any('\t' in ln for ln in lines[:5]) else ','
                if delim==' ':
                    header=re.split(r'\s+', lines[0].strip())
                    for ln in lines[1:]:
                        vals=re.split(r'\s+', ln.strip())
                        if len(vals)>=len(header): yield dict(zip(header, vals))
                else:
                    for r in csv.DictReader(lines, delimiter=delim):
                        yield r
        except Exception as e:
            rejected.append({'input_file':str(p),'reason':'read_failed','error':str(e)[:240]})

    accepted=[]; rejected=[]
    for p in files:
        fhash=_v57_sha256(p)
        for row in iter_rows(p):
            src=first(row,src_alias) or p.stem.split('_')[0]
            obj=first(row,obj_alias) or ''
            z=_v57_to_float(first(row,z_alias))
            v=_v57_to_float(first(row,v_alias))
            rad=_v57_to_float(first(row,r_alias))
            reason=[]
            if not obj: reason.append('missing_object_id')
            if z is None: reason.append('missing_z')
            if v is None or not (0 < v < 1000): reason.append('missing_or_bad_vrot_km_s')
            if rad is None or not (0 < rad < 200): reason.append('missing_or_bad_radius_kpc')
            if reason:
                if len(rejected)<1000:
                    rejected.append({'input_file':str(p),'reason':reason,'columns':list(row.keys())[:40]})
                continue
            canonical='|'.join([str(src),str(obj),str(z),str(v),str(rad),str(p),str(fhash)])
            accepted.append({'source_group':str(src).strip(),'object_id':str(obj).strip(),'z':z,'vrot_km_s':v,'radius_kpc':rad,'raw_source_file':str(p),'raw_source_sha256':fhash,'row_sha256':hashlib.sha256(canonical.encode()).hexdigest()})

    # De-duplicate by source+object+z+v+r
    dedup=[]; seen=set()
    for r in accepted:
        key=(r['source_group'],r['object_id'],round(float(r['z']),6),round(float(r['vrot_km_s']),3),round(float(r['radius_kpc']),3))
        if key in seen: continue
        seen.add(key); dedup.append(r)
    accepted=dedup

    if accepted:
        _v57_write_csv(out_csv, accepted, ['source_group','object_id','z','vrot_km_s','radius_kpc','raw_source_file','raw_source_sha256','row_sha256'])
    else:
        # Write a tiny note artifact, not a template and not promotable.
        _v57_write_json(out_csv.with_suffix('.json'), {'status':'no_highz_rows_autobuilt','candidate_files':[str(p) for p in files[:80]], 'n_rejected':len(rejected), 'note':'No trusted raw high-z Vrot/R rows found automatically. No manual fill required; test remains data-limited.'})
    _v57_write_json(rejected_path, {'n_rejected':len(rejected),'rejected_preview':rejected[:200]})
    diag={'status':'built' if accepted else 'no_rows','candidate_files':[str(p) for p in files[:120]],'n_candidate_files':len(files),'n_rows':len(accepted),'output_csv':str(out_csv) if accepted else None,'rejected_path':str(rejected_path),'source_counts':{}}
    for r in accepted:
        diag['source_counts'][r['source_group']]=diag['source_counts'].get(r['source_group'],0)+1
    _v57_write_json(diag_path, diag)
    return out_csv if accepted else None, diag

